import {
  Bell,
  Building2,
  ChevronDown,
  Compass,
  ExternalLink,
  Factory,
  FileText,
  History,
  Inbox,
  KeyRound,
  LayoutDashboard,
  LogOut,
  Mail,
  Menu,
  MessageSquareText,
  Moon,
  PanelLeftClose,
  PanelLeftOpen,
  Phone,
  Search,
  Settings,
  ShieldCheck,
  Sun,
  Upload,
  UserCog,
  Users,
  type LucideIcon,
} from "lucide-react";

/** The app's icons (Lucide line icons, 1.75 stroke). Decorative: aria-hidden. Names are stable so call sites don't change. */
const ICONS: Record<string, LucideIcon> = {
  dashboard: LayoutDashboard,
  markets: Compass,
  ask: MessageSquareText,
  carriers: Building2,
  contacts: Users,
  documents: FileText,
  inbox: Inbox,
  approvals: ShieldCheck,
  bell: Bell,
  setup: Settings,
  industries: Factory,
  imports: Upload,
  users: UserCog,
  audit: History,
  codes: KeyRound,
  logout: LogOut,
  menu: Menu,
  search: Search,
  sun: Sun,
  moon: Moon,
  collapse: PanelLeftClose,
  expand: PanelLeftOpen,
  chevron: ChevronDown,
  external: ExternalLink,
  phone: Phone,
  mail: Mail,
};

export function Icon({ name, className = "h-4 w-4" }: { name: string; className?: string }) {
  const C = ICONS[name] ?? LayoutDashboard;
  return <C className={className} strokeWidth={1.75} aria-hidden="true" focusable="false" />;
}
